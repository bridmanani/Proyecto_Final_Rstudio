# Análisis Exploratorio de Datos - ENAHO
# Proyecto Final - Ofimatica
## Descripción

Este proyecto presenta un análisis exploratorio de datos (EDA) utilizando la base ENAHO.

## Contenido

- data/: base de datos utilizada.
- scripts/: código en R.
- figures/: gráficos obtenidos durante el análisis.

## Autor
- BRIDGIT OLGA MANANÍ CARRIÓN


Pregunta de investigación:
¿Existe diferencia en la asistencia a un centro educativo según el sexo de la población peruana registrada en la ENAHO 2020?

Análisis:
Para responder la pregunta planteada se elaboró una tabla de contingencia entre las variables sexo y asistencia a un centro educativo. Asimismo, se calcularon los porcentajes relativos por sexo y se construyó un gráfico de barras apiladas con proporciones para visualizar las diferencias existentes entre ambos grupos.

## Conclusiones

Se analizó la relación entre el sexo y la asistencia a un centro educativo utilizando información de la ENAHO 2020.

Los resultados permitieron identificar la distribución porcentual de la población según ambas variables y evidenciaron la utilidad del análisis exploratorio para comprender el comportamiento de los datos.

El gráfico de barras apiladas facilitó la comparación entre categorías y permitió responder la pregunta de investigación planteada.
